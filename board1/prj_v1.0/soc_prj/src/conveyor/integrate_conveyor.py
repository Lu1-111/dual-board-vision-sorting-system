"""Idempotent GP0 AXI-Lite post-generation integration for this TD project.

Run after regenerating design_0. Keeps the vendor block-design XML intact and
inserts the tested router between its protocol converter and original matrix.
The board commissioning build exposes four BTS outputs with bounded jog limits.
"""
from pathlib import Path
import re
from consolidate_clocks import main as consolidate_clocks
from integrate_servo_status import main as integrate_servo_status
from integrate_can import main as integrate_can
from integrate_conveyor_motor import main as integrate_conveyor_motor

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[1]
SIGNALS = {
    "awaddr": (33,"input"), "awprot": (3,"input"), "awvalid": (1,"input"), "awready": (1,"output"),
    "wdata": (32,"input"), "wstrb": (4,"input"), "wvalid": (1,"input"), "wready": (1,"output"),
    "bresp": (2,"output"), "bvalid": (1,"output"), "bready": (1,"input"),
    "araddr": (33,"input"), "arprot": (3,"input"), "arvalid": (1,"input"), "arready": (1,"output"),
    "rdata": (32,"output"), "rresp": (2,"output"), "rvalid": (1,"output"), "rready": (1,"input"),
}


def wrapper():
    ports=["input wire clk, rst_n", "input wire encoder_a, encoder_b", "output wire bts_rpwm, bts_lpwm, bts_r_en, bts_l_en, txs_oe"]
    for side in ("s","m"):
        for name,(width,direction) in SIGNALS.items():
            if side=="m": direction="output" if direction=="input" else "input"
            ports.append(f"{direction} wire "+(f"[{width-1}:0] " if width>1 else "")+side+"_"+name)
    wires=[]
    for name,(width,_) in SIGNALS.items():
        if name in ("awprot","arprot"): continue
        if name in ("awaddr","araddr"): width=12
        wires.append("wire "+(f"[{width-1}:0] " if width>1 else "")+"c_"+name+";")
    route=[".clk(clk)",".rst_n(rst_n)"]
    for side in ("s","m","c"):
        route += [f".{side}_{name}({side}_{name})" for name in SIGNALS if side!="c" or name not in ("awprot","arprot")]
    core=[".aclk(clk)",".aresetn(rst_n)",".estop(1'b0)",".driver_fault(1'b0)",".encoder_a(encoder_a)",".encoder_b(encoder_b)"]
    core += [f".s_axi_{name}(c_{name})" for name in SIGNALS if name not in ("awprot","arprot")]
    core += [f".{name}({name})" for name in ("bts_rpwm", "bts_lpwm", "bts_r_en", "bts_l_en")]
    return "\n".join([
        "// Generated by integrate_conveyor.py. Default is locked; board selects an explicit encoder control/commissioning profile.",
        "module conveyor_gp0 #(parameter integer CLK_HZ=75000000, BENCH_ONLY=1, JOG_ONLY=0, ENCODER_CONNECTED=0, JOG_LIMIT_MS=1000)(",",\n".join(ports),");",
        *wires,
        "// Keep the level shifter disabled while reset settles. External 5 V must already be stable.",
        "localparam integer OE_DELAY_TICKS = (CLK_HZ / 10 > 0) ? CLK_HZ / 10 : 1;",
        "reg [31:0] oe_delay_count;",
        "reg oe_ready;",
        "always @(posedge clk or negedge rst_n) begin",
        "  if (!rst_n) begin oe_delay_count <= 0; oe_ready <= 0; end",
        "  else if (!oe_ready) begin",
        "    if (oe_delay_count == OE_DELAY_TICKS-1) oe_ready <= 1;",
        "    else oe_delay_count <= oe_delay_count + 1'b1;",
        "  end",
        "end",
        "assign txs_oe = rst_n && oe_ready;",
        "axi_lite_route route_inst ("+",\n".join(route)+");",
        "conveyor_axi #(.CLK_HZ(CLK_HZ),.BENCH_ONLY(BENCH_ONLY),.JOG_ONLY(JOG_ONLY),.ENCODER_CONNECTED(ENCODER_CONNECTED),.JOG_LIMIT_MS(JOG_LIMIT_MS)) motor_inst ("+",\n".join(core)+");",
        "endmodule\n"])


def main():
    integrate_can(PROJECT)
    integrate_servo_status(PROJECT)
    consolidate_clocks(PROJECT)
    (HERE/"conveyor_gp0.v").write_text(wrapper(),encoding="utf-8")
    generated=PROJECT/"design_0/hdl/design_0.v"
    text=generated.read_text(encoding="utf-8")
    if "// CONVEYOR_GP0_BEGIN" not in text:
        backup=generated.with_suffix(".v.pre-conveyor")
        if not backup.exists(): backup.write_text(text,encoding="utf-8")
        pattern=r"(AXI_Protocol_Converter_0\s+design_0_AXI_Protocol_Converter_0_Inst\s*\()(.*?)(\);)"
        def replace(match):
            body=match[2]
            for name in SIGNALS:
                old="w_port__AXI_Protocol_Converter_0__ds_axi_"+name
                if old not in body: raise ValueError("Converter port missing: "+name)
                body=body.replace(old,"w_conveyor_up_"+name)
            return match[1]+body+match[3]
        text,count=re.subn(pattern,replace,text,count=1,flags=re.S)
        if count!=1: raise ValueError("Expected exactly one GP0 converter")
        lines=["// CONVEYOR_GP0_BEGIN: run src/conveyor/integrate_conveyor.py after DI regeneration"]
        for name,(width,_) in SIGNALS.items():
            lines.append("wire "+(f"[{width-1}:0] " if width>1 else "")+"w_conveyor_up_"+name+";")
        connections=[".clk(w_port__AXI_Protocol_Converter_0__aclk)",".rst_n(w_port__AXI_Protocol_Converter_0__aresetn)"]
        for name in SIGNALS:
            connections += [f".s_{name}(w_conveyor_up_{name})",f".m_{name}(w_port__AXI_Protocol_Converter_0__ds_axi_{name})"]
        lines += ["conveyor_gp0 conveyor_gp0_inst ("+",\n".join(connections)+");","// CONVEYOR_GP0_END\n"]
        position=text.rfind("endmodule")
        if position<0: raise ValueError("Generated module end missing")
        text=text[:position]+"\n"+"\n".join(lines)+text[position:]
        generated.write_text(text,encoding="utf-8")
    project=PROJECT/"soc_prj.al"
    text=project.read_text(encoding="utf-8")
    backup=project.with_suffix(".al.pre-conveyor")
    if not backup.exists():backup.write_text(text,encoding="utf-8")
    text=re.sub(r'(<Project[^>]* Path=")[^"]*(")',lambda m:m[1]+PROJECT.as_posix()+m[2],text,count=1)
    for index,name in enumerate(["axi_lite_route.v","conveyor_axi.v","conveyor_gp0.v"],100):
        relative="src/conveyor/"+name
        if 'Path="'+relative+'"' in text:continue
        entry=f'''<File Path="{relative}"><FileInfo>
          <Attr Name="UsedInSyn" Val="true"/><Attr Name="UsedInP&R" Val="true"/>
          <Attr Name="BelongTo" Val="design_1"/><Attr Name="CompileOrder" Val="{index}"/>
        </FileInfo></File>\n'''
        text=text.replace("</Verilog>",entry+"</Verilog>",1)
    relative="src/conveyor/conveyor_75m.sdc"
    if 'Path="'+relative+'"' not in text:
        entry=f'''<File Path="{relative}"><FileInfo>
          <Attr Name="UsedInSyn" Val="true"/><Attr Name="UsedInP&R" Val="true"/>
          <Attr Name="BelongTo" Val="constraint_1"/><Attr Name="CompileOrder" Val="3"/>
        </FileInfo></File>\n'''
        text=text.replace("</SDC_FILE>",entry+"</SDC_FILE>",1)
    project.write_text(text,encoding="utf-8")
    integrate_conveyor_motor(PROJECT)
    print("INTEGRATED: GP0 0x80060000..0x80060fff, 75 MHz, BTS outputs, external AB encoder; selected motion profile preserved")


if __name__=="__main__":main()
